"""Remove graphify's broken hyperedge shading from graphify-out/graph.html.

Graphify draws each hyperedge as a filled region behind the nodes it spans and
calls it a convex hull, but the shipped code never computes one: it joins the
member positions in stored order, so scattered points become a self-crossing
star. It draws from an afterDrawing handler with no selection test, so the
triangles render on every frame whether or not anything is selected. Reported
by the owner on 4 August 2026; the same bug was diagnosed and fixed the same
way in pro-360-test (its build/strip_graph_hulls.py) on 2 August 2026.

The bug is upstream in graphify's _hyperedge_script(). It is not patched at
source because that code is shared by every project on this machine and a
release would silently overwrite the fix. Only the generated page is edited.

graph.html is regenerated by graphify, so rerun this after any map refresh.
The hyperedges stay in graph.json, so no knowledge is lost.
"""
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HTML = ROOT / "graphify-out" / "graph.html"
BACKUP = ROOT / "graphify-out" / "graph.html.bak-2026-08-04-prehullstrip"

MARKER = "// Render hyperedges as shaded regions"
HANDLER = "network.on('afterDrawing'"

NOTE = (
    "// Hyperedge shading removed by build/strip_graph_hulls.py.\n"
    "// Graphify joins each region's points in stored order instead of around\n"
    "// the perimeter, so it self-crosses into triangles over the whole canvas.\n"
    "// Rerun that script after any graphify refresh.\n"
)


def block_bounds(html):
    """Start and end of the hyperedge block, by brace matching rather than a
    line count, so a graphify update that reformats the file cannot make this
    cut in the wrong place."""
    start = html.find(MARKER)
    if start == -1:
        return None

    handler = html.find(HANDLER, start)
    if handler == -1:
        raise SystemExit("strip_graph_hulls: found the marker but no afterDrawing "
                         "handler. Graphify's output has changed shape; re-read it "
                         "before cutting.")

    depth, i = 0, handler
    while i < len(html):
        if html[i] == "{":
            depth += 1
        elif html[i] == "}":
            depth -= 1
            if depth == 0:
                end = html.find(");", i)
                if end == -1:
                    raise SystemExit("strip_graph_hulls: handler never closes.")
                return start, end + 2
        i += 1
    raise SystemExit("strip_graph_hulls: unbalanced braces in the handler.")


def main():
    if not HTML.exists():
        print("strip_graph_hulls: no graph.html, skipping")
        return 0

    html = HTML.read_text()
    bounds = block_bounds(html)
    if bounds is None:
        print("strip_graph_hulls: OK, no hyperedge shading present")
        return 0

    start, end = bounds
    if not BACKUP.exists():
        shutil.copy2(HTML, BACKUP)

    stripped = html[:start] + NOTE + html[end:]

    for essential in ("new vis.Network", "vis.DataSet", "on('click'", "searchInput"):
        assert essential in stripped, f"cut removed {essential!r}; refusing to write"

    HTML.write_text(stripped)
    print(f"strip_graph_hulls: removed {end - start} chars of shading code")
    print(f"  graph.html {len(html)} -> {len(stripped)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
